"""Политика запросов кадра: несовершеннолетние не уходят в NanoGPT.

Негатив в промпте (`ADULT_NEG`) — это смягчение, а не запрет: запрос всё равно
уходил бы третьей стороне целиком. Здесь — жёсткий отказ до выхода в сеть.
"""

from __future__ import annotations

import re

UNDERAGE_PATTERNS = (
    # Возраст в цифрах — только рядом с возрастным словом и без склейки с другими цифрами
    # (чтобы «1024x1408» и «55mm» не читались как возраст).
    r"(?<![\d])(?:1[0-7]|[0-9])(?![\d])\s*(?:y/?o\b|years?\s*old|год(?:а|ов)?\b|лет\b)(?![\w])",
    r"(?<![\w])(?:under|младше|моложе)\s*(?:1[0-9]|20|21)(?![\w])",
    r"(?<![\w])(?:underage|minors?|teen(?:ager)?s?|schoolgirl|schoolboy|school\s*kid|"
    r"loli(?:ta)?|shota|jailbait|barely\s*legal|child(?:ren)?|kids?)(?![\w])",
    r"(?<![а-яё])(?:несовершеннолетн\w*|подрост\w*|школьниц\w*|школьник\w*|девочк\w*|"
    r"малолетн\w*|реб[её]н\w*|дет(?:и|ей|сад\w*|ск\w*))(?![а-яё])",
)

_UNDERAGE_RE = re.compile("|".join(UNDERAGE_PATTERNS), re.IGNORECASE)


def underage_violation(text: str) -> bool:
    """True, если в запросе есть маркер несовершеннолетнего.

    Проверка консервативная: фраза с отрицанием («дети на фоне не нужны»)
    тоже будет отклонена — цена ложного отказа ниже цены пропущенного запроса.
    """
    return bool(_UNDERAGE_RE.search(text or ""))
